"""Metadata-only stock archive and original resource-service code guard."""
import argparse, sys
from pathlib import Path

p=argparse.ArgumentParser()
p.add_argument('--disc',type=Path,required=True)
p.add_argument('--framework',type=Path,required=True)
p.add_argument('--output',type=Path,required=True)
p.add_argument('--check',action='store_true')
args=p.parse_args()
sys.path.insert(0,str(args.framework/'tools'))
from aot_overlay_pipeline import Disc
from resident_catalog import collect_entries, executable_range_sha256
disc=Disc(args.disc)
entries=collect_entries(disc,lambda name:name=='MEDRES.MWD')
assert len(entries)==1
ranges=((0x800A804C,0x800A8684),)
guard=executable_range_sha256(disc.read('MEDIEVIL.EXE'),ranges)
text='// Original USA metadata, no asset bytes. Generated by medievil_resident_catalog.py.\n'
text+='static const PSXResidentFile kFiles[] = {\n'
text+=''.join(f'    {{"{n}", {s}u, "{h}"}},\n' for n,l,s,h in entries)
text+='};\nstatic const PSXResidentRange kContract[] = {{0x800A804Cu,0x800A8684u}};\n'
text+=f'static const char* kContractSha256 = "{guard}";\n'
if args.check:assert args.output.read_text()==text,'Resident catalog is stale'
else:args.output.write_text(text,newline='\n')
print(entries[0].path,entries[0].padded_size,guard)
